"""Generate the per-code error pages from the issue catalogue and the test fixtures.

Every worked example is real: it is the issue the validator reports on that code's failing
fixture in xlsform/tests/unit/test_validator.py. Re-run after changing the catalogue:

    python scripts/gen_error_docs.py

Writes docs/errors/<CODE>.md (for GitHub) and xlsform/core/error_docs.py (data for the site
page at /xlsform-docs/errors, which issue links point to).
"""

import json
import os
import string
import sys
from pathlib import Path

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from xlsform.core.issues import CATALOGUE
from xlsform.tests.unit.test_validator import cases, run

STAGES = {
	1: "File",
	2: "Structure",
	3: "Meaning",
	4: "Frappe limits",
	5: "Changes from the published version",
}
SEVERITY = {
	"error": "Error: blocks publishing",
	"warning": "Warning: publish after ticking “I understand”",
	"info": "Advice",
}


def readable(template: str, example: str) -> str:
	"""Show a catalogue template with ‹placeholders›; a bare {hint} becomes the real example."""
	if template.strip() in ("{hint}",):
		return example
	out = []
	for literal, field, _spec, _conv in string.Formatter().parse(template):
		out.append(literal)
		if field is not None:
			out.append(f"‹{field}›")
	return "".join(out)


def main() -> None:
	fixtures = cases()
	entries = []
	for code, entry in sorted(CATALOGUE.items(), key=lambda kv: (kv[1].stage, kv[0])):
		bad, _good, _where = fixtures[code]
		hit = next(i for i in run(bad).issues if i.code == code)
		where = f"{hit.sheet}!{hit.cell}" if hit.sheet and hit.cell else (hit.sheet or "")
		entries.append(
			{
				"code": code,
				"severity": entry.severity,
				"severity_text": SEVERITY[entry.severity],
				"stage": entry.stage,
				"stage_name": STAGES[entry.stage],
				"message": readable(entry.message, hit.message),
				"suggestion": readable(entry.suggestion, hit.suggestion),
				"example": {"where": where, "message": hit.message, "suggestion": hit.suggestion},
			}
		)
	out = os.path.join(ROOT, "xlsform", "core", "error_docs.py")
	Path(out).write_text(
		'"""Generated by scripts/gen_error_docs.py — do not edit."""\n\n'
		+ "ENTRIES = "
		+ json.dumps(entries, ensure_ascii=False, indent=1)
		+ "\n",
		encoding="utf-8",
	)
	docs = os.path.join(ROOT, "docs", "errors")
	os.makedirs(docs, exist_ok=True)
	for e in entries:
		Path(docs, f"{e['code']}.md").write_text(
			f"# {e['code']}\n\n"
			f"**{e['severity_text']}** · stage {e['stage']}, {e['stage_name']}\n\n"
			f"## What it means\n\n{e['message']}\n\n"
			f"## How to fix it\n\n{e['suggestion']}\n\n"
			"## Example\n\n"
			f"An upload that triggers it reports{' at `' + e['example']['where'] + '`' if e['example']['where'] else ''}:\n\n"
			f"> {e['example']['message']}\n>\n> → {e['example']['suggestion']}\n\n"
			"Words in ‹angle quotes› above are filled in with your form's own names, rows and values.\n",
			encoding="utf-8",
		)
	rows = "".join(
		f"| [{e['code']}]({e['code']}.md) | {e['severity']} | {e['stage']} | {e['message']} |\n"
		for e in entries
	)
	Path(docs, "README.md").write_text(
		"# Issue codes\n\nEvery problem the validator reports has a stable code. Errors block publishing; warnings need “I understand the warnings”; advice is optional.\n\n"
		"| Code | Severity | Stage | Meaning |\n| --- | --- | --- | --- |\n" + rows,
		encoding="utf-8",
	)
	print(f"{len(entries)} codes documented")


if __name__ == "__main__":
	main()
